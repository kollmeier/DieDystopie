#!/usr/bin/env python3
"""Build the Lost Tales index and upload-ready context, without modifying the briefing."""
from pathlib import Path
from urllib.parse import quote
import os
import re

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / 'lost-tales'
BRIEF = PROJECT / 'context-briefing.md'
INDEX = PROJECT / 'context-index.md'
CONTEXT = PROJECT / 'context.md'


def readmes(directory):
    """Find READMEs without entering template directories."""
    paths = []
    for root, directories, files in os.walk(directory):
        directories[:] = [name for name in directories if not name.startswith('_')]
        if 'README.md' in files:
            paths.append(Path(root) / 'README.md')
    return sorted(paths)


def link(path):
    rel = path.relative_to(PROJECT).as_posix()
    match = re.search(r'^#\s+(.+?)\s*$', path.read_text(encoding='utf-8-sig'), re.M)
    name = match.group(1) if match else path.parent.name
    return f'- [{name}]({quote(rel, safe="/.-_")})'


sections = [
    ('Grundlagen', [PROJECT / name for name in ('README.md', 'RULES.md', 'THEMES.md', 'LORE-GUARD.md')]),
    ('Strips', readmes(PROJECT / 'strips')),
    ('Figuren', readmes(PROJECT / 'characters')),
    ('Orte', readmes(PROJECT / 'locations')),
    ('Referenzorte (nicht kanonisch)', readmes(PROJECT / 'reference_locations')),
]
lines = ['# Dateiindex', '', 'Automatisch erzeugte Links auf die Quelldateien. Kein eigener Kanon.', '']
for heading, paths in sections:
    existing = [p for p in paths if p.is_file()]
    if not existing:
        continue
    lines += [f'## {heading}', ''] + [link(p) for p in existing] + ['']
INDEX.write_text('\n'.join(lines).rstrip() + '\n', encoding='utf-8')
if not BRIEF.is_file():
    raise SystemExit(f'Missing {BRIEF}')
brief = BRIEF.read_text(encoding='utf-8').strip()
index = INDEX.read_text(encoding='utf-8').strip()
CONTEXT.write_text(
    '<!-- GENERATED by scripts/build_context.py. Edit context-briefing.md instead. -->\n'
    '# Lost Tales – Projektkontext\n\n'
    'Dieses Dokument ist ein exportierbarer Kontext-Schnappschuss. '
    'Die Quelldateien im Repository haben Vorrang.\n\n'
    + brief + '\n\n---\n\n' + index + '\n', encoding='utf-8'
)
print('Updated lost-tales/context-index.md and lost-tales/context.md')
